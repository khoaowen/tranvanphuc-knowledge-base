#!/usr/bin/env python3
"""Rebuild knowledge-gpt/*.md for the manual Custom GPT upload (stdlib only).

Reads only videos the validator reports `published`. Each summary.md is copied whole.
Greedy packing, oldest first, so a new week only appends to the last volume or opens
a new one. At most MAX_FILES files, each at most MAX_FILE_BYTES; if packing cannot fit,
exit 1 and write nothing. Only files carrying the GENERATED marker are ever removed.

Exit codes: 0 ok; 1 failure (nothing written); 2 transcript changed while validating.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import generate_index  # noqa: E402
import validate_summaries  # noqa: E402
from summarize import DISCLAIMER_BANNER  # noqa: E402

MAX_FILES = 20
MAX_FILE_BYTES = 2_000_000
GENERATED = "<!-- generated by scripts/consolidate.py; do not edit -->"
OUT_DIR = "knowledge-gpt"
OVERVIEW = "00-overview.md"
SEPARATOR = "\n\n---\n\n"


class Overflow(Exception):
    pass


def size(text):
    return len(text.encode("utf-8"))


def volume_name(number):
    return f"{number:02d}-summaries.md"


def volume_header(number):
    return f"{GENERATED}\n\n# Knowledge volume {number}\n\n{DISCLAIMER_BANNER}\n\n"


def pack(videos, max_bytes):
    """Greedy oldest-first packing of whole summaries; returns [[video, ...], ...]."""
    volumes, current, used = [], [], 0
    for video in videos:
        body = size(video["summary"]) + size(SEPARATOR)
        header = size(volume_header(len(volumes) + 1))
        if header + body > max_bytes:
            raise Overflow(f"summary {video['name']} alone needs {header + body} bytes, cap is {max_bytes}")
        if current and used + body > max_bytes:
            volumes.append(current)
            current, used = [], 0
            header = size(volume_header(len(volumes) + 1))
        if not current:
            used = header
        current.append(video)
        used += body
    if current:
        volumes.append(current)
    return volumes


def render_volume(number, volume):
    return volume_header(number) + SEPARATOR.join(v["summary"].rstrip("\n") for v in volume) + "\n"


def render_overview(volumes):
    lines = [GENERATED, "", "# Dr. Trần Văn Phúc knowledge base: overview", "", DISCLAIMER_BANNER, "",
             "These files are generated from validated summaries of the doctor's public videos. "
             "Each volume holds complete video summaries, oldest first; every section links to the "
             "video at the matching timestamp. Answer from these summaries only and cite the video.", ""]
    count = sum(len(v) for v in volumes)
    if not count:
        lines += ["No videos have been published yet.", ""]
    else:
        lines += [f"{count} video(s) in {len(volumes)} volume(s).", "", "| Date | Video | Topics | Volume |",
                  "| --- | --- | --- | --- |"]
        rows = [(v, n) for n, vol in enumerate(volumes, 1) for v in vol]
        for video, number in reversed(rows):
            lines.append(f"| {video['date']} | [{generate_index.esc(video['title'])}]({video['url']}) "
                         f"({video['video_id']}) | {', '.join(video['tags'])} | {volume_name(number)} |")
        lines.append("")
    return "\n".join(lines)


def build_files(videos, max_files=None, max_bytes=None):
    max_files, max_bytes = max_files or MAX_FILES, max_bytes or MAX_FILE_BYTES
    volumes = pack(videos, max_bytes)
    files = {OVERVIEW: render_overview(volumes)}
    files.update({volume_name(n): render_volume(n, vol) for n, vol in enumerate(volumes, 1)})
    if len(files) > max_files:
        raise Overflow(f"needs {len(files)} files, cap is {max_files}")
    for name, text in files.items():
        if size(text) > max_bytes:
            raise Overflow(f"{name} needs {size(text)} bytes, cap is {max_bytes}")
    return files


def is_generated(path):
    try:
        return path.read_text(encoding="utf-8").splitlines()[0] == GENERATED
    except (OSError, IndexError, UnicodeDecodeError):
        return False


def consolidate(root, videos_dir, vocabulary_path, max_files=None, max_bytes=None):
    """Write knowledge-gpt/; return the list of changed repo-relative paths."""
    root = Path(root).resolve()
    out = root / OUT_DIR
    videos = generate_index.published_videos(Path(videos_dir).resolve(), vocabulary_path)
    files = build_files(videos, max_files, max_bytes)
    desired = {out / name: text for name, text in files.items()}
    removals = [p for p in sorted(out.glob("*.md")) if p not in desired and is_generated(p)] if out.is_dir() else []
    for path in desired:
        if path.exists() and not is_generated(path):
            raise generate_index.GenerationError(f"refusing to overwrite hand-written {path.relative_to(root)}")
    changed = [p for p, text in desired.items() if generate_index.write_if_changed(p, text)]
    for path in removals:
        path.unlink()
        changed.append(path)
    return [p.relative_to(root).as_posix() for p in changed]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    generate_index.add_arguments(ap)
    args = ap.parse_args(argv)
    root, videos_dir, vocabulary = generate_index.resolve_paths(args)
    try:
        changed = consolidate(root, videos_dir, vocabulary)
    except validate_summaries.TranscriptChanged as exc:
        print(f"transcript changed during validation ({exc})", file=sys.stderr)
        return 2
    except Overflow as exc:
        print(f"consolidate: overflow, nothing written: {exc}", file=sys.stderr)
        return 1
    except (generate_index.GenerationError, OSError, ValueError) as exc:
        print(f"consolidate: {exc}", file=sys.stderr)
        return 1
    print(f"consolidate: {len(changed)} file(s) changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
