#!/usr/bin/env python3
"""Generate the README index block and topics/<tag>.md pages (stdlib only).

Reads only videos the validator reports `published`. Never writes videos/*.
Output is deterministic and idempotent: unchanged inputs change no file.
Only files carrying the GENERATED marker are ever removed.

Exit codes: 0 ok; 1 failure (nothing written); 2 transcript changed while validating.
"""

import argparse
import json
import os
import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import validate_summaries  # noqa: E402
from summarize import DISCLAIMER_BANNER  # noqa: E402

INDEX_START = "<!-- index:start -->"
INDEX_END = "<!-- index:end -->"
GENERATED = "<!-- generated by scripts/generate_index.py; do not edit -->"
RESERVED_SLUGS = {"vocabulary"}


class GenerationError(Exception):
    pass


def slugify(tag):
    """Unaccented, lowercase, hyphenated; Vietnamese `đ` becomes `d`."""
    text = unicodedata.normalize("NFC", tag).casefold().replace("đ", "d")
    text = "".join(c for c in unicodedata.normalize("NFD", text) if not unicodedata.combining(c))
    slug = re.sub(r"[^a-z0-9]+", "-", text).strip("-") or "untitled"
    return slug + "-topic" if slug in RESERVED_SLUGS else slug


def header_fields(summary):
    fields = {}
    for line in summary.splitlines():
        m = re.match(r"^- \*\*([^:*]+):\*\*\s*(.*)$", line)
        if m:
            fields.setdefault(m.group(1).strip(), m.group(2).strip())
        if line.startswith("## "):
            break
    return fields


def published_videos(videos_dir, vocabulary_path):
    """Published videos, oldest first (directory names start with YYYY-MM-DD)."""
    import queue_state
    videos = []
    for entry in queue_state.list_videos(videos_dir):
        video_dir = entry["dir"]
        if not validate_summaries.validate_video(video_dir, vocabulary_path)["published"]:
            continue
        summary = (video_dir / "summary.md").read_text(encoding="utf-8")
        meta = json.loads((video_dir / "metadata.json").read_text(encoding="utf-8"))
        fields = header_fields(summary)
        first = summary.splitlines()[0][2:].strip() if summary.startswith("# ") else video_dir.name
        tags, seen = [], set()
        for raw in fields.get("Topics", "").split(","):
            tag = raw.strip()
            if tag and validate_summaries.norm(tag) not in seen:
                seen.add(validate_summaries.norm(tag))
                tags.append(tag)
        videos.append({
            "dir": video_dir, "name": video_dir.name, "video_id": entry["video_id"],
            "title": meta.get("title") or first,
            "date": meta.get("published_at") or fields.get("Published", ""),
            "url": meta.get("url") or fields.get("URL", ""),
            "tags": tags, "summary": summary,
        })
    videos.sort(key=lambda v: v["name"])
    return videos


def esc(text):
    return re.sub(r"([\[\]|])", r"\\\1", text)


def build_topics(videos):
    """{slug: {"tag": display, "videos": [video, ...]}} sorted by slug, videos oldest first."""
    topics = {}
    for video in videos:
        for tag in video["tags"]:
            slot = topics.setdefault(slugify(tag), {"tags": set(), "videos": []})
            slot["tags"].add(tag)
            if video not in slot["videos"]:
                slot["videos"].append(video)
    return {slug: {"tag": sorted(slot["tags"], key=lambda t: (validate_summaries.norm(t), t))[0],
                   "videos": slot["videos"]}
            for slug, slot in sorted(topics.items())}


def link_base(root, videos_dir, from_dir):
    return Path(os.path.relpath(videos_dir, from_dir)).as_posix()


def render_index_block(videos, topics, base):
    lines = [INDEX_START, "<!-- generated by scripts/generate_index.py; do not edit between the index markers -->",
             "", DISCLAIMER_BANNER, ""]
    if not videos:
        lines += ["No videos have been published yet.", ""]
    else:
        lines += ["### Videos by date", "", "| Date | Video | Topics |", "| --- | --- | --- |"]
        for video in reversed(videos):
            tags = ", ".join(f"[{esc(t)}](topics/{slugify(t)}.md)" for t in video["tags"])
            lines.append(f"| {video['date']} | [{esc(video['title'])}]({base}/{video['name']}/summary.md) "
                         f"([transcript]({base}/{video['name']}/transcript.md)) | {tags} |")
        lines += ["", "### Videos by topic", ""]
        lines += [f"- [{esc(t['tag'])}](topics/{slug}.md) ({len(t['videos'])})" for slug, t in topics.items()]
        lines.append("")
    lines.append(INDEX_END)
    return "\n".join(lines)


def render_topic(slug, topic, base):
    lines = [GENERATED, "", f"# Topic: {topic['tag']}", "", DISCLAIMER_BANNER, ""]
    for video in reversed(topic["videos"]):
        lines.append(f"- {video['date']} — [{esc(video['title'])}]({base}/{video['name']}/summary.md) "
                     f"([transcript]({base}/{video['name']}/transcript.md))")
    lines += ["", "[Back to the index](../README.md)", ""]
    return "\n".join(lines)


def splice_readme(text, block):
    start, end = text.find(INDEX_START), text.find(INDEX_END)
    if start != -1 and end > start:
        return text[:start] + block + text[end + len(INDEX_END):]
    return text.rstrip("\n") + "\n\n## Index\n\n" + block + "\n"


def is_generated(path):
    try:
        return path.read_text(encoding="utf-8").splitlines()[0] == GENERATED
    except (OSError, IndexError, UnicodeDecodeError):
        return False


def write_if_changed(path, content):
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def generate(root, videos_dir, vocabulary_path):
    """Write README block and topic pages; return the list of changed paths."""
    root, videos_dir = Path(root).resolve(), Path(videos_dir).resolve()
    readme = root / "README.md"
    if not readme.is_file():
        raise GenerationError("README.md not found")
    videos = published_videos(videos_dir, vocabulary_path)
    topics = build_topics(videos)
    topics_dir = root / "topics"

    desired = {topics_dir / f"{slug}.md": render_topic(slug, t, link_base(root, videos_dir, topics_dir))
               for slug, t in topics.items()}
    new_readme = splice_readme(readme.read_text(encoding="utf-8"),
                               render_index_block(videos, topics, link_base(root, videos_dir, root)))
    removals = [p for p in sorted(topics_dir.glob("*.md")) if p not in desired and is_generated(p)] \
        if topics_dir.is_dir() else []
    for path in desired:
        if path.exists() and not is_generated(path):
            raise GenerationError(f"refusing to overwrite hand-written {path.relative_to(root)}")

    changed = []
    for path, content in desired.items():
        if write_if_changed(path, content):
            changed.append(path)
    for path in removals:
        path.unlink()
        changed.append(path)
    if write_if_changed(readme, new_readme):
        changed.append(readme)
    return [p.relative_to(root).as_posix() for p in changed]


def add_arguments(ap):
    ap.add_argument("--root", default=".")
    ap.add_argument("--videos-dir", default=None, help="default: <root>/videos")
    ap.add_argument("--vocabulary", default=None, help="default: <root>/topics/vocabulary.md")


def resolve_paths(args):
    root = Path(args.root)
    return root, Path(args.videos_dir) if args.videos_dir else root / "videos", \
        Path(args.vocabulary) if args.vocabulary else root / "topics" / "vocabulary.md"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    add_arguments(ap)
    args = ap.parse_args(argv)
    root, videos_dir, vocabulary = resolve_paths(args)
    try:
        changed = generate(root, videos_dir, vocabulary)
    except validate_summaries.TranscriptChanged as exc:
        print(f"transcript changed during validation ({exc})", file=sys.stderr)
        return 2
    except (GenerationError, OSError, ValueError) as exc:
        print(f"generate_index: {exc}", file=sys.stderr)
        return 1
    print(f"generate_index: {len(changed)} file(s) changed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
